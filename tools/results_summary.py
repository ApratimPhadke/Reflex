def stuck_range(text):
    vals = [float(v) for v in re.findall(r"ground truth ([\d.]+) mm", text)]
    return f"{min(vals):.1f}-{max(vals):.1f} mm over {len(vals)} runs (strip: 10 mm)" if vals else None


def value(path, rx):
    p = ROOT / path
    if not p.exists():
        return "**missing file**"
    text = p.read_text(errors="replace")
    if rx is None:
        v = stuck_range(text)
    else:
        m = re.search(rx, text, re.M)
        v = m.group(1).strip() if m else None
    if v and re.fullmatch(r"\d+\.\d{4,}", v):          # a raw float from a JSON file: millimetres
        v = f"{float(v):.1f} mm"
    return re.sub(r"\s+", " ", v).replace("|", "vs") if v else "**not found in file**"


def table():
    out = ["| Measurement | Target | Result | Source |", "|---|---|---|---|"]
    for what, target, path, rx in ROWS:
        out.append(f"| {what} | {target} | {value(path, rx)} | [`{Path(path).name}`]({path}) |")
    return "\n".join(out)


def main():
    t = table()
    if "--print" in sys.argv:
        print(t)
        return 0
    readme = ROOT / "README.md"
    s = readme.read_text()
    if START not in s or END not in s:
        print("README.md has no results markers", file=sys.stderr)
        return 1
    i, j = s.index(START) + len(START), s.index(END)
    readme.write_text(s[:i] + "\n" + t + "\n" + s[j:])
    print("README.md results table updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
